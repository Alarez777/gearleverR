#!/usr/bin/env python3
"""Extracts t("...")/tf("...") messages into po/gearlever-r.pot."""

from __future__ import annotations

import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "crates/gearlever/src"
CALL = re.compile(r"\btf?\s*\(\s*\"((?:[^\"\\]|\\.)*)\"")

ESCAPES = {
    "\\": "\\",
    '"': '"',
    "n": "\n",
    "t": "\t",
    "r": "\r",
    "0": "\0",
}


def unescape(value: str) -> str:
    result = []
    iterator = iter(value)
    for character in iterator:
        if character != "\\":
            result.append(character)
            continue
        try:
            escape = next(iterator)
        except StopIteration:
            result.append("\\")
            break
        result.append(ESCAPES.get(escape, escape))
    return "".join(result)


def escape(value: str) -> str:
    value = value.replace("\\", "\\\\").replace('"', '\\"')
    return value.replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")


def main() -> int:
    messages: dict[str, list[str]] = {}

    for path in sorted(SRC.rglob("*.rs")):
        relative = path.relative_to(ROOT)
        source = path.read_text(encoding="utf-8")
        for match in CALL.finditer(source):
            message = unescape(match.group(1))
            if message:
                line = source.count("\n", 0, match.start()) + 1
                messages.setdefault(message, []).append(f"{relative}:{line}")

    output = [
        "# Translation template for Gear LeverR.",
        "# This file is generated by scripts/extract-strings.py; do not edit it by hand.",
        'msgid ""',
        'msgstr ""',
        '"Project-Id-Version: gearlever-r 0.1.0\\n"',
        '"Report-Msgid-Bugs-To: https://github.com/Alarez777/gearleverR/issues\\n"',
        f'"POT-Creation-Date: {datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M+0000")}\\n"',
        '"MIME-Version: 1.0\\n"',
        '"Content-Type: text/plain; charset=UTF-8\\n"',
        '"Content-Transfer-Encoding: 8bit\\n"',
        "",
    ]

    for message in sorted(messages):
        for reference in messages[message]:
            output.append(f"#: {reference}")
        output.append(f'msgid "{escape(message)}"')
        output.append('msgstr ""')
        output.append("")

    destination = ROOT / "po/gearlever-r.pot"
    destination.parent.mkdir(exist_ok=True)
    destination.write_text("\n".join(output), encoding="utf-8")
    print(f"{len(messages)} messages -> {destination.relative_to(ROOT)}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
